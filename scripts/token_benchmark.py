#!/usr/bin/env python3
"""Measure the context the arsenal adds to every Claude Code session, from the real files.

Usage:
  token_benchmark.py            # write docs/BENCHMARK.md
  token_benchmark.py --check    # fail when docs/BENCHMARK.md is out of date (CI)
  token_benchmark.py --json     # print the measurement as JSON, write nothing
  token_benchmark.py --live [--task NAME] [--runs N] [--model M] [--max-budget-usd X]
                                # PAID: run the task set with and without the plugin through `claude -p`,
                                # record the reported usage in docs/benchmark-live.json, rewrite the report.
                                # Tasks not run this time are kept only while the Claude Code version, model
                                # and arsenal version are the same; otherwise the record starts again.

The offline modes are deterministic and need no network: sizes come from the canonical sources through
build.py's loaders, and the SessionStart hook outputs come from running the commands in hooks/hooks.json in
an empty temporary project (and again with a full lessons ledger). Tokens are estimated as characters / 4;
that is an approximation, not a tokenizer count. Time budget: about 2 seconds offline. Standard library only.
"""
import argparse
import contextlib
import datetime
import io
import json
import os
import shlex
import shutil
import statistics
import subprocess
import sys
import tempfile
from pathlib import Path

import build

ROOT = build.ROOT
REPORT = ROOT / "docs" / "BENCHMARK.md"
LIVE_RECORD = ROOT / "docs" / "benchmark-live.json"
LESSONS_DIR = build.AGENTS / "skills" / "lessons-learned" / "scripts"
PLUGIN_ROOT_VAR = "${CLAUDE_PLUGIN_ROOT}"
CHARS_PER_TOKEN = 4
APPROXIMATION = f"tokens = characters / {CHARS_PER_TOKEN}, rounded: an estimate, not a tokenizer count"
NOTICE = ("<!-- Generated by scripts/token_benchmark.py from the files in this repository. Do not edit. "
          "Regenerate: python3 scripts/token_benchmark.py -->")
HOOK_TIMEOUT = 20
HOOK_CONTEXT_CAP = 10_000  # documented cap on a hook's additionalContext
HOOK_ENV_DROPPED = ("HANDOFF_SNAPSHOT", "LESSONS_FILE", "ARSENAL_GUARD", "CLAUDE_PROJECT_DIR")
LIVE_TIMEOUT = 600
LIVE_DEFAULTS = {"task": None, "runs": 1, "model": "haiku", "max_budget_usd": 0.25}
USAGE_FIELDS = ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens")
RUN_CONDITIONS = ("claude_version", "model", "arsenal_version")  # results are comparable only when these match
LIVE_TASKS = {
    "overhead": {
        "about": "one turn, no tools: the fixed cost of a session",
        "prompt": "Reply with the single word: ok",
        "files": {}, "flags": [],
    },
    "bugfix": {
        "about": "read one file and fix a one-line bug",
        "prompt": "calc.py has a bug: add(2, 2) returns 0. Fix it.",
        "files": {"calc.py": "def add(a, b):\n    return a - b\n"},
        "flags": ["--permission-mode", "acceptEdits", "--allowed-tools", "Read", "Edit", "Write"],
    },
}


def tokens(chars):
    return round(chars / CHARS_PER_TOKEN)


def sized(component, source, chars):
    return {"component": component, "source": source, "chars": chars, "tokens": tokens(chars)}


def listing(entries):
    """One line per entry, the way a plugin's skills and subagents are announced to the model."""
    return "\n".join(f"- {build.PLUGIN_NAME}:{name}: {description}" for name, description in entries)


def skill_files(names):
    """(name, description, SKILL.md chars, [reference file chars]) per skill."""
    rows = []
    for name in names:
        directory = build.AGENTS / "skills" / name
        text = build.read(directory / "SKILL.md")
        block, _ = build.split_frontmatter(text, name)
        references = [len(build.read(path)) for path in sorted(directory.glob("references/**/*.md"))]
        rows.append((name, build.parse_frontmatter(block, name)["description"], len(text), references))
    return rows


def session_start_commands(source="startup"):
    groups = json.loads(build.read(ROOT / "hooks" / "hooks.json"))["hooks"].get("SessionStart", [])
    return [hook["command"] for group in groups
            if not group.get("matcher") or source in group["matcher"].split("|")
            for hook in group["hooks"] if hook.get("type") == "command"]


def hook_argv(command):
    """The first alternative of a `python3 X || python X` hook command, run with this interpreter."""
    first = command.split(" || ")[0].replace(PLUGIN_ROOT_VAR, ROOT.as_posix())
    return [sys.executable, *shlex.split(first)[1:]]


def hook_context(stdout):
    """The text a hook adds to the context: install path replaced by its variable, cut at the host's cap."""
    try:
        text = json.loads(stdout)["hookSpecificOutput"]["additionalContext"]
    except (ValueError, KeyError, TypeError):
        text = stdout.strip()
    return text.replace(str(ROOT), PLUGIN_ROOT_VAR).replace(ROOT.as_posix(), PLUGIN_ROOT_VAR)[:HOOK_CONTEXT_CAP]


def run_session_start(project, state):
    """{hook label: context text} from running every SessionStart hook command in `project`."""
    env = {key: value for key, value in os.environ.items() if key not in HOOK_ENV_DROPPED}
    env.update(TMPDIR=str(state), TEMP=str(state), TMP=str(state), CLAUDE_PLUGIN_ROOT=str(ROOT),
               PYTHONDONTWRITEBYTECODE="1")
    stdin = json.dumps({"session_id": "token-benchmark", "transcript_path": "", "cwd": str(project),
                        "permission_mode": "default", "hook_event_name": "SessionStart", "source": "startup"})
    outputs = {}
    for command in session_start_commands():
        argv = hook_argv(command)
        done = subprocess.run(argv, cwd=project, env=env, input=stdin, capture_output=True, text=True,
                              encoding="utf-8", timeout=HOOK_TIMEOUT, check=False)
        label = " ".join([Path(argv[1]).name, *argv[2:]])
        if done.returncode != 0:  # a crashed hook must not be reported as one that adds nothing
            raise RuntimeError(f"SessionStart hook `{label}` exited {done.returncode}: "
                               f"{(done.stderr.strip().splitlines() or ['no stderr'])[-1]}")
        outputs[label] = hook_context(done.stdout)
    return outputs


def fill_ledger(project):
    """Write the worst-case ledger: the active cap of lessons, every field at its length cap."""
    sys.path.insert(0, str(LESSONS_DIR))
    bytecode, sys.dont_write_bytecode = sys.dont_write_bytecode, True  # leave no __pycache__ in the plugin
    try:
        import lessons
    finally:
        sys.dont_write_bytecode = bytecode
        sys.path.remove(str(LESSONS_DIR))
    ledger = Path(project) / ".agents" / "lessons.md"
    for index in range(lessons.ACTIVE_CAP):
        fields = [part for name in ("mistake", "cause", "rule", "check") for part in (
            f"--{name}", " ".join(f"{name[:2]}{index}n{word}" for word in range(lessons.FIELD_MAX)))]
        with contextlib.redirect_stdout(io.StringIO()):
            lessons.main(["--file", str(ledger), "add", "--tags", "benchmark", *fields])
    return lessons.ACTIVE_CAP


def measure_hooks():
    """(empty-project outputs, full-ledger outputs, lessons in the full ledger)."""
    with tempfile.TemporaryDirectory() as temp:
        empty, full, state = (Path(temp) / name for name in ("empty", "full", "state"))
        for directory in (empty, full, state):
            directory.mkdir()
        lesson_count = fill_ledger(full)
        return run_session_start(empty, state), run_session_start(full, state), lesson_count


def claude_install(sources, scope):
    """What `install --target claude` adds for one scope: (unconditional rules, path-scoped rules, blocks).

    Derived from the install manifest and the generated files. A Claude Code rule file loads every session
    unless it starts with `paths:` frontmatter, whatever its source `trigger` says.
    """
    generated = build.generate(sources)
    always, scoped, blocks = {}, {}, {}
    for target, row_scope, kind, name, source, _, _ in build.manifest_rows(sources):
        if target != "claude" or row_scope != scope or kind not in ("file", "block"):
            continue
        text = generated[source] if source in generated else build.read(ROOT / source)
        if kind == "block":
            blocks[name] = text
        elif text.startswith("---\npaths:"):
            scoped[name] = text
        else:
            always[name] = text
    return always, scoped, blocks


def spread(component, sizes):
    return {"component": component, "files": len(sizes), "min": min(sizes), "median": round(statistics.median(sizes)),
            "max": max(sizes), "total": sum(sizes), "total_tokens": tokens(sum(sizes))}


def route(name, parts, hook_delta):
    chars = sum(part["chars"] for part in parts)
    return {"route": name, "chars": chars, "tokens": tokens(chars),
            "worst_chars": chars + hook_delta, "worst_tokens": tokens(chars + hook_delta)}


def load_live():
    """The recorded live runs, or None when there are none; ValueError when the record cannot be reported."""
    if not LIVE_RECORD.is_file():
        return None
    record = json.loads(build.read(LIVE_RECORD))
    try:
        arms = [task[arm] for task in record["tasks"].values() for arm in ("with", "without")]
        valid = all(isinstance(record[key], str) for key in ("recorded", *RUN_CONDITIONS)) and all(
            isinstance(runs, list) and runs and all(
                isinstance(run[field], (int, float)) for run in runs for field in (*USAGE_FIELDS, "total_cost_usd"))
            for runs in arms)
    except (KeyError, TypeError, AttributeError):
        valid = False
    if not valid:
        raise ValueError(f"{LIVE_RECORD.name}: each task needs a non-empty `with` and `without` list of runs "
                         "carrying the usage fields (delete the file or run --live again)")
    return record


def measure():
    sources = build.load_sources()
    skills = skill_files(sources["skills"])
    agents = sources["subagents"]
    empty, full, lesson_count = measure_hooks()
    plugin = [
        sized(f"Skill listing ({len(skills)} names and descriptions)", ".agents/skills/*/SKILL.md frontmatter",
              len(listing((name, description) for name, description, _, _ in skills))),
        sized(f"Subagent listing ({len(agents)} names and descriptions)", ".agents/subagents/subagent-definitions.json",
              len(listing((agent["name"], agent["description"]) for agent in agents))),
        *(sized(f"SessionStart hook: `{label}`", "hooks/hooks.json, run in an empty project", len(text))
          for label, text in empty.items()),
    ]
    worst = [sized(f"SessionStart hook: `{label}`", f"same hook, ledger of {lesson_count} lessons at the field cap",
                   len(text)) for label, text in full.items() if text != empty[label]]
    hook_delta = sum(len(full[label]) - len(empty[label]) for label in empty)

    rules, scoped, _ = claude_install(sources, "global")
    _, _, blocks = claude_install(sources, "project")
    rule_part = sized(f"Rules without a path scope ({len(rules)})", "dist/claude/rules/",
                      sum(len(text) for text in rules.values()))
    block_parts = [sized(f"`{name}` block", "installer, project scope", len(text)) for name, text in blocks.items()]
    return {
        "approximation": APPROXIMATION,
        "arsenal_version": sources["version"],
        "always_on": plugin + [rule_part] + block_parts,
        "worst_case_hooks": worst,
        "routes": [
            route("Plugin only", plugin, hook_delta),
            route("Plugin + `install --global --target claude`", plugin + [rule_part], hook_delta),
            route("Plugin + `install --target claude` in a project", plugin + [rule_part] + block_parts, hook_delta),
        ],
        "unconditional_rules": sorted(Path(name).stem for name in rules),
        "path_scoped_rules": sorted(Path(name).stem for name in scoped),
        "on_demand": [
            spread("SKILL.md (one per skill, loaded when the skill is invoked)", [size for _, _, size, _ in skills]),
            spread("Skill reference files (a skill reads the one it needs)",
                   [size for _, _, _, sizes in skills for size in sizes]),
            spread("Subagent prompts (loaded in the subagent's own context)", [len(a["body"]) for a in agents]),
            spread("Path-scoped rules (loaded when a matching file is read)", [len(t) for t in scoped.values()]),
        ],
        "live": load_live(),
    }


def number(value):
    return f"{value:,}"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "| :--- |" + " ---: |" * (len(header) - 1)]
    return lines + ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]


def arm_mean(runs, field):
    return sum(run[field] for run in runs) / len(runs)


def live_rows(record):
    rows = []
    for name in LIVE_TASKS:
        task = record["tasks"].get(name)
        if not task:
            rows.append((f"`{name}`", "not yet run", "", "", "", "", ""))
            continue
        for arm in ("with", "without"):
            runs = task[arm]
            rows.append((f"`{name}`, {arm} plugin", len(runs),
                         *(number(round(arm_mean(runs, field))) for field in USAGE_FIELDS),
                         f"{arm_mean(runs, 'total_cost_usd'):.4f}"))
    return rows


def input_side(runs):
    return round(sum(arm_mean(runs, field) for field in USAGE_FIELDS[:3]))


def render_live(record, estimate):
    lines = ["## Live comparison (with and without the plugin)", ""]
    tasks = "; ".join(f"`{name}` ({task['about']})" for name, task in LIVE_TASKS.items())
    how = (f"`python3 scripts/token_benchmark.py --live` runs a fixed task set ({tasks}) through "
           "`claude -p --output-format json`, once with `--plugin-dir` and once without, in an empty temporary "
           "project with user settings and MCP servers excluded, and records the `usage` and `total_cost_usd` "
           "fields the CLI reports. It spends real money on your account and is never run in CI.")
    if not record:
        return lines + [how, "", "Not yet run: no `docs/benchmark-live.json` is recorded, so there are no live numbers."]
    lines += [how, "", f"Last recorded {record['recorded']} with Claude Code {record['claude_version']}, model "
              f"`{record['model']}`, arsenal {record['arsenal_version']}. Means over the runs of each arm. "
              "Token columns are summed over the turns of a run, so they are billed tokens, not context size.", ""]
    lines += table(("Task and arm", "Runs", "Input", "Cache write", "Cache read", "Output", "Cost (USD)"),
                   live_rows(record))
    fixed = record["tasks"].get("overhead")
    if fixed:
        added = input_side(fixed["with"]) - input_side(fixed["without"])
        lines += ["", f"On `overhead` the plugin added {number(added)} input-side tokens (input + cache write + cache "
                  f"read, with minus without). The offline estimate for the plugin-only route is {number(estimate)}."]
    return lines + ["", "A sample this small shows that the mode works and what one session costs. "
                    "It is not evidence about savings or quality on real work."]


def render(result):
    lines = [NOTICE, "", "# Context Overhead Benchmark", "",
             "What the arsenal adds to the context of every Claude Code session before any work starts, "
             "measured from the files in this repository. It is a cost, not a saving. "
             f"Estimate: {result['approximation']}.", "",
             "## Always-on components", ""]
    lines += table(("Component", "Characters", "Tokens (est.)"),
                   [(f"{part['component']} ({part['source']})", number(part["chars"]), number(part["tokens"]))
                    for part in result["always_on"]])
    lines += ["", "Worst case for the hooks (the only always-on part that grows with project state):", ""]
    lines += table(("Component", "Characters", "Tokens (est.)"),
                   [(f"{part['component']} ({part['source']})", number(part["chars"]), number(part["tokens"]))
                    for part in result["worst_case_hooks"]])
    lines += ["", "## Total per install route", ""]
    lines += table(("Route", "Characters", "Tokens (est.)", "Characters, full ledger", "Tokens (est.), full ledger"),
                   [(r["route"], number(r["chars"]), number(r["tokens"]), number(r["worst_chars"]),
                     number(r["worst_tokens"])) for r in result["routes"]])
    lines += ["", "Rules that load in every Claude Code session after the installer runs: "
              + ", ".join(f"`{name}`" for name in result["unconditional_rules"]) + ". "
              "A generated Claude rule file loads unconditionally unless it carries `paths:` frontmatter, so "
              "a rule without globs is always loaded on this target, whatever its trigger. Path-scoped: "
              + ", ".join(f"`{name}`" for name in result["path_scoped_rules"]) + ".", "",
              "## Loaded only when used", "",
              "Not part of the totals above. Sizes in characters.", ""]
    lines += table(("Content", "Files", "Min", "Median", "Max", "Total", "Total tokens (est.)"),
                   [(part["component"], *(number(part[key]) for key in
                                          ("files", "min", "median", "max", "total", "total_tokens")))
                    for part in result["on_demand"]])
    lines += ["", *render_live(result["live"], result["routes"][0]["tokens"]), "",
              "## Limits of this measurement", "",
              "- The listing format (`- arsenal:<name>: <description>`) approximates how the host announces skills "
              "and subagents. It can be off in either direction: the host may shorten descriptions to fit its own "
              "listing budget, and it adds framing of its own. Where a live `overhead` run is recorded above, "
              "compare it with the estimate.",
              f"- Hook output that embeds the install path is measured with the path written as `{PLUGIN_ROOT_VAR}`; "
              "a real install adds the length of its own path.",
              f"- A hook's output is cut at {HOOK_CONTEXT_CAP:,} characters, the documented cap on `additionalContext`; "
              "the lessons hook caps its own output below that, so the full-ledger case is not truncated by the host.",
              "- Event-driven hook output is not counted: the snapshot shown again after a compaction, and the "
              "stop gate's message when it blocks.",
              "- The installer wraps each block in two marker lines, which are not counted.",
              "- Nothing here measures what the skills save or cost while they run. See [EVALS.md](EVALS.md).", ""]
    return "\n".join(lines)


def live_command(task, model, budget, with_plugin):
    command = ["claude", "-p", "--output-format", "json", "--model", model, "--max-budget-usd", str(budget),
               "--no-session-persistence", "--setting-sources", "project", "--strict-mcp-config"]
    if with_plugin:
        command += ["--plugin-dir", str(ROOT)]
    return command + task["flags"]


def live_run(task, model, budget, with_plugin):
    """One `claude -p` run in a fresh project; returns the usage fields the CLI reported."""
    with tempfile.TemporaryDirectory() as project, tempfile.TemporaryDirectory() as state:
        for name, text in task["files"].items():
            (Path(project) / name).write_text(text, encoding="utf-8")
        env = {**os.environ, "TMPDIR": state, "TEMP": state, "TMP": state}  # the plugin's hook state files go here
        done = subprocess.run(live_command(task, model, budget, with_plugin), cwd=project, input=task["prompt"],
                              env=env, capture_output=True, text=True, encoding="utf-8", timeout=LIVE_TIMEOUT,
                              check=False)
    try:
        result = json.loads(done.stdout)
        if result["is_error"]:
            raise ValueError(result.get("subtype"))
        return {**{field: result["usage"][field] for field in USAGE_FIELDS},
                "total_cost_usd": result["total_cost_usd"], "num_turns": result["num_turns"]}
    except (ValueError, KeyError, TypeError) as error:
        raise RuntimeError(f"claude -p failed (exit {done.returncode}): {error!r} {done.stderr.strip()[:300]}") from error


def live(options):
    if not shutil.which("claude"):
        raise RuntimeError("the `claude` CLI is not on PATH")
    version = subprocess.run(["claude", "--version"], capture_output=True, text=True, check=True).stdout.split()[0]
    names = [options.task] if options.task else list(LIVE_TASKS)
    record = {"recorded": datetime.date.today().isoformat(), "claude_version": version, "model": options.model,
              "arsenal_version": build.read(ROOT / "VERSION").strip(), "tasks": {}}
    try:
        previous = load_live()
    except ValueError:
        previous = None  # a damaged record is replaced
    if previous and all(previous[key] == record[key] for key in RUN_CONDITIONS):
        record["tasks"] = previous["tasks"]
    for name in names:
        record["tasks"][name] = {
            arm: [live_run(LIVE_TASKS[name], options.model, options.max_budget_usd, arm == "with")
                  for _ in range(options.runs)] for arm in ("with", "without")}
    LIVE_RECORD.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if docs/BENCHMARK.md is stale")
    mode.add_argument("--json", action="store_true", help="print the measurement as JSON")
    mode.add_argument("--live", action="store_true", help="paid: run the tasks with and without the plugin")
    parser.add_argument("--task", choices=sorted(LIVE_TASKS), help="--live: run one task instead of all")
    parser.add_argument("--runs", type=int, help="--live: runs per arm (default 1)")
    parser.add_argument("--model", help="--live: model alias (default haiku)")
    parser.add_argument("--max-budget-usd", type=float, help="--live: cost ceiling per run (default 0.25)")
    parser.set_defaults(**LIVE_DEFAULTS)
    options = parser.parse_args(argv)
    if options.runs < 1:
        parser.error("--runs must be at least 1")
    if not options.live and any(getattr(options, name) != value for name, value in LIVE_DEFAULTS.items()):
        parser.error("--task, --runs, --model and --max-budget-usd apply only with --live")

    try:
        if options.live:
            live(options)
        result = measure()
    except (build.SourceError, OSError, ValueError, KeyError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if options.json:
        print(json.dumps(result, indent=2))
        return 0
    report = render(result)
    if options.check:
        if not REPORT.is_file() or REPORT.read_bytes() != report.encode("utf-8"):
            print("stale docs/BENCHMARK.md (run python3 scripts/token_benchmark.py)", file=sys.stderr)
            return 1
        print("up to date: docs/BENCHMARK.md")
        return 0
    REPORT.write_bytes(report.encode("utf-8"))
    print(f"wrote {REPORT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
