#!/usr/bin/env python3
"""Keep the real-task eval results machine-readable and render their table in docs/EVALS.md.

Usage:
  eval_report.py                       # rewrite the generated block in docs/EVALS.md from docs/eval-results.json
  eval_report.py --check               # fail when that block is out of date (CI)
  eval_report.py --record harness.json --label NAME [--outcomes outcomes.json] [--note TEXT]
                                       # store one `claude plugin eval --json` result under NAME (replacing a
                                       # record with the same label), then rewrite the block

`--record` keeps, per case, arm and run: score, cost (agent plus judge, as the harness reports it), judge
cost, turns, duration, each grader's verdict, the outcome checks from eval_outcomes.py, and the token usage
from the run's trace when the run was kept with `--keep-temp` (the harness JSON itself carries no token
counts; without the trace they are recorded as null). Nothing here calls a model: recording and rendering
are offline and deterministic. Time budget: under a second. Standard library only.
"""
import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "docs" / "eval-results.json"
DOC = ROOT / "docs" / "EVALS.md"
START = "<!-- eval-results:start (generated by scripts/eval_report.py from docs/eval-results.json; do not edit) -->"
END = "<!-- eval-results:end -->"
ARMS = (("with", "with plugin"), ("without", "without plugin"))
USAGE_FIELDS = ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens")
INPUT_FIELDS = USAGE_FIELDS[:3]
HEADER = ("Task", "Arm", "Runs", "Mean score", "Graders passed", "Outcome checks passed",
          "Cost per run (USD)", "Input tokens per run", "Output tokens per run", "Turns per run")


def trace_usage(trace_path):
    """Token usage from the `result` event of a run's trace, or None when the trace is gone or has none."""
    try:
        lines = Path(trace_path).read_text(encoding="utf-8").splitlines()
    except (OSError, TypeError):
        return None
    for line in reversed(lines):
        try:
            event = json.loads(line)
        except ValueError:
            continue
        if isinstance(event, dict) and event.get("type") == "result" and isinstance(event.get("usage"), dict):
            return {field: event["usage"].get(field, 0) for field in USAGE_FIELDS}
    return None


def run_record(run, outcomes):
    return {
        "score": run["score"],
        "cost_usd": run["costUsd"],
        "judge_cost_usd": run.get("judgeCostUsd", 0),
        "turns": run["turns"],
        "duration_seconds": run.get("durationSeconds"),
        "error": run.get("error"),
        "tokens": trace_usage(run.get("tracePath")),
        "graders": {grader["name"]: {"passed": grader["passed"], "scored": grader.get("scored", True)}
                    for grader in run["graders"]},
        "outcomes": {name: check["status"] for name, check in outcomes.items()},
    }


def case_record(case, outcomes):
    record = {}
    for arm, _ in ARMS:
        runs = case["arms"].get(arm, [])
        checked = outcomes.get(arm, [])
        record[arm] = [run_record(run, checked[index] if index < len(checked) else {})
                       for index, run in enumerate(runs)]
    return record


def entry(harness, outcomes, label, note):
    """One recorded harness result. KeyError when the JSON is not a `claude plugin eval --json` result."""
    suite = harness["suite"]
    plugins = suite.get("plugins") or [{}]
    cases = {case["name"]: case_record(case, outcomes.get(case["name"], {})) for case in harness["cases"]}
    return {
        "label": label,
        "note": note,
        "recorded": harness["startedAt"][:10],
        "claude_version": harness["claudeVersion"],
        "arsenal_version": plugins[0].get("version"),
        "model": suite.get("modelOverride"),
        "judge_model": suite.get("judgeModel"),
        "runs_per_arm": max((len(runs) for case in cases.values() for runs in case.values()), default=0),
        "cost_usd": harness["costUsd"],
        "partial": bool(harness.get("partial")),
        "cases": cases,
    }


def load_results():
    if not RESULTS.is_file():
        return {"runs": []}
    results = json.loads(RESULTS.read_text(encoding="utf-8"))
    if not isinstance(results, dict) or not isinstance(results.get("runs"), list):
        raise ValueError(f"{RESULTS.name}: expected an object with a `runs` list")
    return results


def with_entry(results, new):
    """The results with `new` replacing the record of the same label, or appended."""
    kept = [run for run in results["runs"] if run["label"] != new["label"]]
    return {"runs": kept + [new]}


def mean(values, digits):
    values = [value for value in values if value is not None]
    if not values:
        return "not recorded"
    return f"{statistics.fmean(values):,.{digits}f}"


def tally(runs, field, counts):
    """`name passed/total` per grader or check, in first-seen order."""
    names = list(dict.fromkeys(name for run in runs for name in run[field]))
    return "<br>".join(counts(name, [run[field][name] for run in runs if name in run[field]]) for name in names)


def grader_count(name, verdicts):
    passed = sum(1 for verdict in verdicts if verdict["passed"])
    indicator = "" if all(verdict["scored"] for verdict in verdicts) else " (indicator, not scored)"
    return f"`{name}` {passed}/{len(verdicts)}{indicator}"


def outcome_count(name, statuses):
    undecided = [status for status in statuses if status not in ("pass", "fail")]
    extra = f" ({len(undecided)} {undecided[0]})" if undecided else ""
    return f"`{name}` {statuses.count('pass')}/{len(statuses)}{extra}"


def tokens(runs, fields):
    return mean([sum(run["tokens"][field] for field in fields) if run["tokens"] else None for run in runs], 0)


def arm_row(case, arm_name, runs):
    return (f"`{case}`", arm_name, str(len(runs)), mean([run["score"] for run in runs], 2),
            tally(runs, "graders", grader_count), tally(runs, "outcomes", outcome_count) or "none defined",
            mean([run["cost_usd"] for run in runs], 4), tokens(runs, INPUT_FIELDS), tokens(runs, USAGE_FIELDS[3:]),
            mean([run["turns"] for run in runs], 1))


def table(rows):
    lines = ["| " + " | ".join(HEADER) + " |", "|" + " :--- |" * len(HEADER)]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def render_entry(run):
    model = run["model"] or "each case's own"
    partial = " (PARTIAL: the cost ceiling stopped the run)" if run["partial"] else ""
    lines = [f"### `{run['label']}` ({run['recorded']})", "",
             f"Claude Code {run['claude_version']}, arsenal {run['arsenal_version']}, model `{model}`, "
             f"judge `{run['judge_model']}`, {run['runs_per_arm']} run(s) per arm, "
             f"total cost {run['cost_usd']:.4f} USD{partial}."]
    if run["note"]:
        lines += ["", run["note"]]
    rows = [arm_row(case, arm_name, arms[arm]) for case, arms in run["cases"].items()
            for arm, arm_name in ARMS if arms.get(arm)]
    return lines + ["", *table(rows)]


def render(results):
    """The generated block, markers included."""
    if not results["runs"]:
        body = ["No run is recorded yet."]
    else:
        body = []
        for run in results["runs"]:
            body += [*render_entry(run), ""]
        body.pop()
    return "\n".join([START, "", *body, "", END])


def replace_block(document, block):
    """The document with the text between the markers replaced. ValueError when the markers are missing."""
    if document.count(START) != 1 or document.count(END) != 1 or document.index(START) > document.index(END):
        raise ValueError(f"{DOC.name}: expected exactly one generated block between the eval-results markers")
    return document[:document.index(START)] + block + document[document.index(END) + len(END):]


def record(options):
    harness = json.loads(options.record.read_text(encoding="utf-8"))
    outcomes = json.loads(options.outcomes.read_text(encoding="utf-8")) if options.outcomes else {}
    results = with_entry(load_results(), entry(harness, outcomes, options.label, options.note))
    RESULTS.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when docs/EVALS.md is out of date")
    mode.add_argument("--record", type=Path, metavar="HARNESS_JSON", help="store a `claude plugin eval --json` result")
    parser.add_argument("--label", help="--record: name of the recorded run, for example smoke or weekly")
    parser.add_argument("--outcomes", type=Path, help="--record: JSON written by eval_outcomes.py")
    parser.add_argument("--note", default="", help="--record: one sentence printed above the table")
    options = parser.parse_args(argv)
    if bool(options.record) != bool(options.label) or (not options.record and (options.outcomes or options.note)):
        parser.error("--record needs --label, and --label, --outcomes and --note apply only with --record")
    try:
        if options.record:
            record(options)
        current = DOC.read_text(encoding="utf-8")
        wanted = replace_block(current, render(load_results()))
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"error: {error!r}" if isinstance(error, KeyError) else f"error: {error}", file=sys.stderr)
        return 1
    if options.check:
        if current != wanted:
            print("error: docs/EVALS.md is out of date; run python3 scripts/eval_report.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
