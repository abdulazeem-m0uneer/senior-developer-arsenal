#!/usr/bin/env python3
"""Run the arsenal hook scripts under an agent other than the Claude Code plugin (installer route).

Usage (hook input is JSON on stdin; the installer writes these commands into each agent's hook config):
  agent_hook.py <target> SessionStart   # inject the operating core and the lessons, record the guard baseline
  agent_hook.py <target> Stop           # the test and lesson gate (guard.py stop)
  <target>: codex | gemini | cursor | copilot | antigravity

The scripts themselves speak the Claude Code hook contract. This adapter is the only per-agent code: it
renames the agent's input fields to that contract, runs the steps listed for the event in steps.json
(generated by scripts/build.py from hooks/hooks.json, beside this file), and prints one JSON object in the
agent's own output contract. Contracts, from each agent's documentation (docs/TARGETS.md has the links and
says which were run live):
  codex        session_id, cwd; additionalContext; Stop {"decision":"block","reason"}
  gemini       session_id, cwd; additionalContext; AfterAgent {"decision":"deny","reason"}
  cursor       conversation_id, workspace_roots, status, loop_count; {"additional_context"};
               stop {"followup_message"}
  copilot      sessionId, cwd; {"additionalContext"}; agentStop {"decision":"block","reason"}
  antigravity  conversationId, workspacePaths, error; {"injectSteps":[{"systemMessage":{"systemMessage"}}]};
               Stop {"decision":"continue","reason"}, any other decision lets the agent stop
Prints nothing when there is nothing to say (Antigravity, whose documentation defines no empty output, gets
an object that changes nothing). Never breaks the session: any error exits 0 silently, and an unknown
target or event does nothing. Time budget: one interpreter start per step, each step bounded by its own
timeout from steps.json. Standard library only.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(os.path.abspath(__file__)).parent  # not resolved: under --link the steps live beside the link
CLAUDE_COMPATIBLE = ("codex", "gemini")


def first_text(value):
    return next((item for item in value if isinstance(item, str)), None) if isinstance(value, list) else None


def claude_input(target, event, data):
    """The agent's hook input with the field names the scripts read; None when the gate must stay out."""
    payload = dict(data)
    if target == "cursor":
        payload["session_id"] = data.get("conversation_id") or data.get("session_id")
        payload["cwd"] = first_text(data.get("workspace_roots"))
        if event == "Stop":
            if data.get("status") != "completed":  # aborted or failed: the user stopped it, do not push on
                return None
            payload["stop_hook_active"] = bool(data.get("loop_count"))
    elif target == "copilot":
        payload["session_id"] = data.get("sessionId")
    elif target == "antigravity":
        payload["session_id"] = data.get("conversationId")
        payload["cwd"] = first_text(data.get("workspacePaths"))
        if event == "Stop" and data.get("error"):
            return None
    elif target not in CLAUDE_COMPATIBLE:
        return None
    payload["hook_event_name"] = event
    return payload


def run_steps(event, payload):
    """(context texts, stop reason) read from the Claude-contract output of each step."""
    steps = json.loads((HERE / "steps.json").read_text(encoding="utf-8")).get(event, [])
    stdin, texts, reason = json.dumps(payload).encode("utf-8"), [], ""
    for step in steps:
        try:
            done = subprocess.run([sys.executable, str(HERE / step["script"]), *step["args"]], input=stdin,
                                  capture_output=True, timeout=step["timeout"])
            output = done.stdout.decode("utf-8", "replace").strip()
            parsed = json.loads(output) if output else {}
        except ValueError:
            texts.append(output)  # plain text is context, as it is under Claude Code
            continue
        except (OSError, subprocess.SubprocessError):
            continue  # one broken step must not cost the others
        if not isinstance(parsed, dict):
            continue
        if parsed.get("decision") == "block" and parsed.get("reason"):
            reason = reason or str(parsed["reason"])
        specific = parsed.get("hookSpecificOutput")
        if isinstance(specific, dict) and specific.get("additionalContext"):
            texts.append(str(specific["additionalContext"]))
    return texts, reason


def session_output(target, text):
    if target == "cursor":
        return {"additional_context": text}
    if target == "copilot":
        return {"additionalContext": text}
    if target == "antigravity":
        return {"injectSteps": [{"systemMessage": {"systemMessage": text}}]}
    return {"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": text}}


def stop_output(target, reason):
    if target == "cursor":
        return {"followup_message": reason}
    if target == "antigravity":
        return {"decision": "continue", "reason": reason}
    return {"decision": "deny" if target == "gemini" else "block", "reason": reason}


def answer(target, event, data):
    """The object to print in the agent's contract, or None for silence."""
    payload = claude_input(target, event, data)
    texts, reason = run_steps(event, payload) if payload else ([], "")
    if event == "SessionStart" and texts:
        return session_output(target, "\n\n".join(texts))
    if event == "Stop" and reason:
        return stop_output(target, reason)
    if target == "antigravity" and payload:
        return {"decision": "allow"} if event == "Stop" else {}
    return None


def hook_input():
    try:
        data = json.loads(sys.stdin.buffer.read().decode("utf-8", "replace"))
        return data if isinstance(data, dict) else {}
    except (ValueError, OSError):
        return {}


def main():
    try:
        target, event = sys.argv[1:3]
        result = answer(target, event, hook_input())
        if result is not None:
            print(json.dumps(result))
    except Exception:  # a hook must never break the session
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
